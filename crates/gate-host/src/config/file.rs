/// `[workspace] projects`: a package manager's workspace, or explicit globs of project roots.
#[derive(Clone, Debug, Eq, PartialEq)]
pub enum ProjectSources {
    /// `"pnpm"`: the `packages` globs of `pnpm-workspace.yaml`.
    Pnpm,
    /// `"npm"`: the `workspaces` globs of the root `package.json` (npm and yarn).
    Npm,
    /// A list of globs; every directory they match that holds a tracked file is a project.
    Globs(Vec<String>),
}

impl<'de> Deserialize<'de> for ProjectSources {
    fn deserialize<D: Deserializer<'de>>(deserializer: D) -> Result<Self, D::Error> {
        struct SourcesVisitor;

        impl<'de> Visitor<'de> for SourcesVisitor {
            type Value = ProjectSources;

            fn expecting(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
                formatter.write_str("\"pnpm\", \"npm\", or a list of globs of project roots")
            }

            fn visit_str<E: de::Error>(self, value: &str) -> Result<Self::Value, E> {
                match value {
                    "pnpm" => Ok(ProjectSources::Pnpm),
                    "npm" => Ok(ProjectSources::Npm),
                    other => Err(E::custom(format!(
                        "{other:?} is not a project source; expected \"pnpm\", \"npm\", or a list of globs"
                    ))),
                }
            }

            fn visit_seq<A: SeqAccess<'de>>(
                self,
                mut sequence: A,
            ) -> Result<Self::Value, A::Error> {
                let mut globs = Vec::new();

                while let Some(glob) = sequence.next_element::<String>()? {
                    globs.push(glob);
                }

                Ok(ProjectSources::Globs(globs))
            }
        }

        deserializer.deserialize_any(SourcesVisitor)
    }
}

impl JsonSchema for ProjectSources {
    fn schema_name() -> Cow<'static, str> {
        Cow::Borrowed("ProjectSources")
    }

    fn json_schema(_generator: &mut SchemaGenerator) -> Schema {
        json_schema!({
            "anyOf": [
                { "type": "string", "enum": ["pnpm", "npm"] },
                { "type": "array", "items": { "type": "string" } }
            ]
        })
    }
}

