/// `[hooks]`: the gate commands each git hook runs, and a time budget for hook runs.
#[derive(Debug, Default)]
pub struct HooksSection {
    /// `--budget` in seconds for the checks the hooks run.
    pub budget: Option<u64>,
    /// The gate commands of each hook, in order.
    pub hooks: BTreeMap<HookName, Vec<String>>,
}

impl<'de> Deserialize<'de> for HooksSection {
    fn deserialize<D: Deserializer<'de>>(deserializer: D) -> Result<Self, D::Error> {
        struct HooksVisitor;

        impl<'de> Visitor<'de> for HooksVisitor {
            type Value = HooksSection;

            fn expecting(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
                formatter
                    .write_str("a table of git hooks, each a list of gate commands, and budget")
            }

            fn visit_map<A: MapAccess<'de>>(self, mut map: A) -> Result<HooksSection, A::Error> {
                let mut section = HooksSection::default();

                while let Some(key) = map.next_key::<String>()? {
                    if key == "budget" {
                        section.budget = Some(map.next_value()?);
                    } else {
                        let hook = HookName::try_from(key).map_err(de::Error::custom)?;
                        let commands = map.next_value()?;
                        section.hooks.insert(hook, commands);
                    }
                }

                Ok(section)
            }
        }

        deserializer.deserialize_map(HooksVisitor)
    }
}

impl JsonSchema for HooksSection {
    fn schema_name() -> Cow<'static, str> {
        Cow::Borrowed("HooksSection")
    }

    fn json_schema(_generator: &mut SchemaGenerator) -> Schema {
        let mut properties = serde_json::Map::new();
        properties.insert(
            "budget".to_owned(),
            serde_json::json!({
                "type": "integer",
                "minimum": 1,
                "description": "--budget in seconds for the checks the hooks run."
            }),
        );
        for hook in super::names::HOOKS {
            properties.insert(
                (*hook).to_owned(),
                serde_json::json!({ "type": "array", "items": { "type": "string" } }),
            );
        }
        json_schema!({
            "type": "object",
            "description": "The gate commands each git hook runs, and a time budget for hook runs.",
            "properties": properties,
            "additionalProperties": false
        })
    }
}

