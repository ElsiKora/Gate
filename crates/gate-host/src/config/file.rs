/// `[ci.github]`: the GitHub Actions workflow `gate sync` writes.
#[derive(Debug, Deserialize, JsonSchema)]
#[serde(deny_unknown_fields, rename_all = "kebab-case")]
pub struct CiGithub {
    /// The workflow file, relative to the repository root.
    pub workflow: RelativePath,
    /// The workflow's display name; defaults to `Gate`.
    pub name: Option<String>,
    /// The branches whose pushes, and pull requests into them, run the workflow: GitHub branch
    /// globs, written to the workflow as given (`["**"]` is every branch); defaults to `["main"]`.
    #[serde(default)]
    pub branches: Vec<String>,
    /// The checkout action, pinned by commit: `actions/checkout@<40 hex digits>`.
    pub checkout: String,
    /// The runner of the generated `changes` job and of the `aggregate` job, which runs `bash` and
    /// `jq` (GitHub's hosted runners have both); defaults to `ubuntu-24.04`.
    pub runs_on: Option<String>,
    /// Steps every job runs after the checkout (installing a toolchain, for example).
    #[serde(default)]
    pub setup: Vec<CiStep>,
    /// The jobs, by id; the id and the name are kept as written.
    #[serde(default)]
    pub jobs: BTreeMap<JobId, CiJob>,
    /// The id of one more generated job that needs every other job and fails unless each of them
    /// succeeded or was skipped: the single check branch protection requires. None: no such job.
    pub aggregate: Option<JobId>,
}

/// A job of the generated workflow.
#[derive(Debug, Deserialize, JsonSchema)]
#[serde(deny_unknown_fields, rename_all = "kebab-case")]
pub struct CiJob {
    /// The job's display name.
    pub name: String,
    /// The runner; defaults to `ubuntu-24.04`.
    pub runs_on: Option<String>,
    /// The job's token permissions; defaults to `{ contents = "read" }`.
    #[serde(default)]
    pub permissions: BTreeMap<String, String>,
    /// Service containers, written to the workflow as given.
    #[serde(default)]
    pub services: BTreeMap<String, serde_json::Value>,
    /// Steps after the checkout and the workflow's `setup`, before the gate commands.
    #[serde(default)]
    pub steps: Vec<CiStep>,
    /// Steps after the gate commands (uploading reports, for example); each may carry an `if`.
    #[serde(default)]
    pub after: Vec<CiStep>,
    /// The gate commands the job runs, in order; `check` commands get `--no-overrides`. They run
    /// at the repository root.
    pub run: Vec<String>,
    /// The directory, relative to the repository root, the job's `run` steps (in `steps` and
    /// `after`) run in when they set none; the gate commands always run at the root.
    pub working_directory: Option<RelativePath>,
    /// The checkout's `fetch-depth` (0: the whole history). Unset: the whole history when a gate
    /// command runs a rule that reads history, or checks a pushed range or a revision; else the
    /// checkout's default, the tip alone.
    pub fetch_depth: Option<u64>,
    /// `--budget` in seconds for the job's checks, with `--budget-fails`.
    pub budget: Option<u64>,
    /// The projects the job needs: it is skipped when none of them changed. Empty: it always runs.
    #[serde(default)]
    pub projects: Vec<String>,
    /// A time limit for the job, in minutes.
    pub timeout_minutes: Option<u64>,
}

/// A step of a job: an action pinned by commit, or a shell command.
#[derive(Debug, Deserialize, JsonSchema)]
#[serde(deny_unknown_fields, rename_all = "kebab-case")]
pub struct CiStep {
    /// The step's display name.
    pub name: Option<String>,
    /// An action pinned by commit: `<owner>/<repo>[/<path>]@<40 hex digits>`.
    pub uses: Option<String>,
    /// The action's inputs.
    #[serde(default)]
    pub with: BTreeMap<String, serde_json::Value>,
    /// A shell command.
    pub run: Option<String>,
    /// Environment variables of the step.
    #[serde(default)]
    pub env: BTreeMap<String, String>,
    /// A `run` step's directory, relative to the repository root; defaults to the job's
    /// `working-directory`.
    pub working_directory: Option<RelativePath>,
    /// A GitHub expression that decides whether an `after` step runs, such as
    /// `always() && hashFiles('reports/**') != ''`.
    #[serde(rename = "if")]
    pub condition: Option<String>,
}

/// A `[tools]` entry: an external program pinned by version and checksum per platform, put on the
/// `PATH` of the steps that name it in `tools`.
#[derive(Clone, Debug, Deserialize, JsonSchema)]
#[serde(deny_unknown_fields, rename_all = "kebab-case")]
pub struct Tool {
    /// The tool's version: a label for messages. The sha256 of each target is what pins it.
    pub version: String,
    /// One download per target triple (`aarch64-apple-darwin`, `x86_64-unknown-linux-musl`, ...).
    pub targets: BTreeMap<String, ToolTarget>,
}

/// One platform's download of a tool.
#[derive(Clone, Debug, Deserialize, JsonSchema)]
#[serde(deny_unknown_fields, rename_all = "kebab-case")]
pub struct ToolTarget {
    /// An `https://` URL (plain `http` only to `127.0.0.1`, `localhost` or `[::1]`) of an archive
    /// (`.tar.gz`, `.tgz`, `.tar.xz`, `.tar`, `.zip`) or of the executable itself.
    pub url: String,
    /// The download's sha256, 64 lowercase hex digits.
    pub sha256: String,
    /// The executable's path inside the archive; required for an archive.
    pub bin: Option<String>,
}

/// A value written either as a string or as a table.
trait StringOrTable: Sized {
    type Table: for<'de> Deserialize<'de>;
    const EXPECTING: &'static str;

    fn from_str(value: &str) -> Result<Self, String>;
    fn from_table(table: Self::Table) -> Result<Self, String>;
}

fn string_or_table<'de, D: Deserializer<'de>, T: StringOrTable>(
    deserializer: D,
) -> Result<T, D::Error> {
    struct StringOrTableVisitor<T>(PhantomData<T>);

    impl<'de, T: StringOrTable> Visitor<'de> for StringOrTableVisitor<T> {
        type Value = T;

        fn expecting(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
            formatter.write_str(T::EXPECTING)
        }

        fn visit_str<E: de::Error>(self, value: &str) -> Result<T, E> {
            T::from_str(value).map_err(E::custom)
        }

        fn visit_map<A: MapAccess<'de>>(self, map: A) -> Result<T, A::Error> {
            let table = T::Table::deserialize(de::value::MapAccessDeserializer::new(map))?;
            T::from_table(table).map_err(de::Error::custom)
        }
    }

    deserializer.deserialize_any(StringOrTableVisitor(PhantomData))
}
