/// A `[plugins.<name>]` entry: the source, options shared by the plugin's rules, and extra read
/// grants. Always a table.
#[derive(Clone, Debug, Eq, JsonSchema, PartialEq)]
#[serde(deny_unknown_fields, rename_all = "kebab-case")]
pub struct PluginSpec {
    /// Where the plugin is fetched from: `"<owner>/<repo>:<plugin>@<version>"`.
    pub source: PluginSource,
    /// Options shared by all of the plugin's rules, such as a source layout.
    pub options: Option<serde_json::Value>,
    /// A JSON file with the shared options, relative to this `gate.toml`.
    pub options_file: Option<RelativePath>,
    /// Paths outside the project the plugin may read, relative to the repository root (not to this
    /// `gate.toml`).
    #[serde(default)]
    pub reads: Vec<RepositoryPath>,
}

/// What `[plugins.<name>]` reads into, before the string form is refused.
#[derive(Deserialize)]
#[serde(deny_unknown_fields, rename_all = "kebab-case")]
struct PluginTable {
    source: PluginSource,
    options: Option<serde_json::Value>,
    options_file: Option<RelativePath>,
    #[serde(default)]
    reads: Vec<RepositoryPath>,
}

impl StringOrTable for PluginSpec {
    type Table = PluginTable;
    const EXPECTING: &'static str = "a table with source = \"<owner>/<repo>:<plugin>@<version>\" and optional options, options-file and reads";

    fn from_str(value: &str) -> Result<Self, String> {
        Err(format!(
            "a plugin entry is a table; write {{ source = {value:?} }}"
        ))
    }

    fn from_table(table: PluginTable) -> Result<Self, String> {
        if table.options.is_some() && table.options_file.is_some() {
            return Err("options and options-file are both set; keep one".to_owned());
        }
        Ok(Self {
            source: table.source,
            options: table.options,
            options_file: table.options_file,
            reads: table.reads,
        })
    }
}

impl<'de> Deserialize<'de> for PluginSpec {
    fn deserialize<D: Deserializer<'de>>(deserializer: D) -> Result<Self, D::Error> {
        string_or_table(deserializer)
    }
}

/// A rule level as configuration sets it.
#[derive(Clone, Copy, Debug, Eq, Hash, Ord, PartialEq, PartialOrd)]
pub enum Setting {
    /// The rule (or aspect) does not run, or its findings are dropped.
    Off,
    /// The rule reports at this level.
    On(crate::findings::Level),
}

impl Setting {
    /// Parses `"error"`, `"warning"`, `"note"` or `"off"`.
    ///
    /// # Errors
    /// Fails, with a message saying what is expected, on any other value.
    pub fn parse(value: &str) -> Result<Self, String> {
        use crate::findings::Level;

        match value {
            "error" => Ok(Self::On(Level::Error)),
            "warning" => Ok(Self::On(Level::Warning)),
            "note" => Ok(Self::On(Level::Note)),
            "off" => Ok(Self::Off),
            other => Err(format!(
                "{other:?} is not a level; expected \"error\", \"warning\", \"note\" or \"off\""
            )),
        }
    }
}

impl fmt::Display for Setting {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::Off => formatter.write_str("off"),
            Self::On(level) => level.fmt(formatter),
        }
    }
}

impl<'de> Deserialize<'de> for Setting {
    fn deserialize<D: Deserializer<'de>>(deserializer: D) -> Result<Self, D::Error> {
        let value = String::deserialize(deserializer)?;
        Self::parse(&value).map_err(de::Error::custom)
    }
}

impl JsonSchema for Setting {
    fn schema_name() -> Cow<'static, str> {
        Cow::Borrowed("Setting")
    }

    fn inline_schema() -> bool {
        true
    }

    fn json_schema(_generator: &mut SchemaGenerator) -> Schema {
        json_schema!({ "type": "string", "enum": ["error", "warning", "note", "off"] })
    }
}

/// A `[rules]` entry: a level, or a table.
#[derive(Clone, Debug, Default, Eq, PartialEq)]
pub struct RuleEntry {
    /// The level of the rule's aspects that `levels` does not name; unset keeps the level the
    /// preset gives, or `error` when no preset names the rule.
    pub level: Option<Setting>,
    /// The repository's own written rule this rule enforces, printed with each finding.
    pub norm: Option<String>,
    /// Levels of single aspects, by aspect name.
    pub levels: BTreeMap<Name, Setting>,
    /// Norms of single aspects, by aspect name.
    pub norms: BTreeMap<Name, String>,
    /// The rule's options, validated against the rule's schema.
    pub options: Option<serde_json::Value>,
    /// A JSON file with the rule's options, relative to this `gate.toml`.
    pub options_file: Option<RelativePath>,
}

/// The table form of a `[rules]` entry.
#[derive(Deserialize, JsonSchema)]
#[serde(deny_unknown_fields, rename_all = "kebab-case")]
struct RuleTable {
    /// The level of the rule's aspects that `levels` does not name; unset keeps the level the
    /// preset gives, or `error` when no preset names the rule.
    level: Option<Setting>,
    /// The repository's own written rule this rule enforces, printed with each finding.
    norm: Option<String>,
    /// Levels of single aspects: `{ <aspect> = "warning" }`.
    #[serde(default)]
    levels: BTreeMap<Name, Setting>,
    /// Norms of single aspects: `{ <aspect> = "RULE-X-001" }`.
    #[serde(default)]
    norms: BTreeMap<Name, String>,
    /// The rule's options, validated against the rule's schema. Not with `options-file`.
    options: Option<serde_json::Value>,
    /// A JSON file with the rule's options, relative to this `gate.toml`. Not with `options`.
    options_file: Option<RelativePath>,
}

impl StringOrTable for RuleEntry {
    type Table = RuleTable;
    const EXPECTING: &'static str = "a level (\"error\", \"warning\", \"note\", \"off\") or a table with level, norm, levels, norms, options or options-file";

    fn from_str(value: &str) -> Result<Self, String> {
        Setting::parse(value).map(|level| Self {
            level: Some(level),
            ..Self::default()
        })
    }

    fn from_table(table: RuleTable) -> Result<Self, String> {
        if table.options.is_some() && table.options_file.is_some() {
            return Err("options and options-file are both set; keep one of them".to_owned());
        }

        if table
            .norm
            .as_deref()
            .is_some_and(|norm| norm.trim().is_empty())
        {
            return Err("norm is empty; name the written rule, or remove the key".to_owned());
        }

        if let Some((aspect, _)) = table.norms.iter().find(|(_, norm)| norm.trim().is_empty()) {
            return Err(format!(
                "norms.{aspect} is empty; name the written rule, or remove the key"
            ));
        }

        Ok(Self {
            level: table.level,
            norm: table.norm,
            levels: table.levels,
            norms: table.norms,
            options: table.options,
            options_file: table.options_file,
        })
    }
}

impl<'de> Deserialize<'de> for RuleEntry {
    fn deserialize<D: Deserializer<'de>>(deserializer: D) -> Result<Self, D::Error> {
        string_or_table(deserializer)
    }
}

impl JsonSchema for RuleEntry {
    fn schema_name() -> Cow<'static, str> {
        Cow::Borrowed("RuleEntry")
    }

    fn json_schema(generator: &mut SchemaGenerator) -> Schema {
        let level = generator.subschema_for::<Setting>();
        let table = generator.subschema_for::<RuleTable>();
        json_schema!({ "anyOf": [level, table] })
    }
}

