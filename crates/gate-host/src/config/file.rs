/// A `[suites]` entry: a list of steps, or a table with the steps and `fail-fast`.
#[derive(Clone, Debug, Default, Eq, PartialEq)]
pub struct Suite {
    /// The steps, run in order.
    pub steps: Vec<Name>,
    /// Stop at the first failing step instead of running every step.
    pub fail_fast: bool,
}

/// The table form of a `[suites]` entry.
#[derive(Deserialize, JsonSchema)]
#[serde(deny_unknown_fields, rename_all = "kebab-case")]
struct SuiteTable {
    /// The steps, run in order.
    steps: Vec<Name>,
    /// Stop at the first failing step instead of running every step.
    #[serde(default)]
    fail_fast: bool,
}

impl<'de> Deserialize<'de> for Suite {
    fn deserialize<D: Deserializer<'de>>(deserializer: D) -> Result<Self, D::Error> {
        struct SuiteVisitor;

        impl<'de> Visitor<'de> for SuiteVisitor {
            type Value = Suite;

            fn expecting(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
                formatter.write_str("a list of steps, or a table with steps and fail-fast")
            }

            fn visit_seq<A: SeqAccess<'de>>(self, sequence: A) -> Result<Suite, A::Error> {
                let steps =
                    Vec::<Name>::deserialize(de::value::SeqAccessDeserializer::new(sequence))?;
                Ok(Suite {
                    steps,
                    fail_fast: false,
                })
            }

            fn visit_map<A: MapAccess<'de>>(self, map: A) -> Result<Suite, A::Error> {
                let table = SuiteTable::deserialize(de::value::MapAccessDeserializer::new(map))?;
                Ok(Suite {
                    steps: table.steps,
                    fail_fast: table.fail_fast,
                })
            }
        }

        deserializer.deserialize_any(SuiteVisitor)
    }
}

impl JsonSchema for Suite {
    fn schema_name() -> Cow<'static, str> {
        Cow::Borrowed("Suite")
    }

    fn json_schema(generator: &mut SchemaGenerator) -> Schema {
        let list = generator.subschema_for::<Vec<Name>>();
        let table = generator.subschema_for::<SuiteTable>();
        json_schema!({ "anyOf": [list, table] })
    }
}

