/// One `gate.toml`: the repository root's or a project's.
///
/// Sections marked "root only" are configuration errors in a project's file. The root's `[rules]`
/// holds repository-scope rules, and project settings for sets of projects go in `[[profiles]]`;
/// when the root is itself the only project (no `[workspace]`, or a workspace that lists `"."`), it
/// also holds `[project]` and project-scope rules.
#[derive(Debug, Default, Deserialize, JsonSchema)]
#[serde(deny_unknown_fields, rename_all = "kebab-case")]
#[schemars(title = "gate.toml")]
pub struct ConfigFile {
    /// Root only, required there: the core this repository pins.
    pub gate: Option<GateSection>,
    /// Root only: how projects are discovered. Without it the root is the only project.
    pub workspace: Option<WorkspaceSection>,
    /// The project's name and the presets it starts from.
    pub project: Option<ProjectSection>,
    /// The plugins this file's rules, presets and generators come from.
    #[serde(default)]
    #[schemars(with = "BTreeMap<PluginName, PluginSpec>")]
    pub plugins: BTreeMap<PluginName, Spanned<PluginSpec>>,
    /// Language settings of the project, by language id, passed to every plugin that declares the
    /// language (each language plugin documents its keys).
    #[serde(default)]
    #[schemars(with = "BTreeMap<Name, serde_json::Map<String, serde_json::Value>>")]
    pub languages: BTreeMap<Name, Spanned<serde_json::Value>>,
    /// Rule settings: a level, or a table with level, norm, per-aspect levels and norms, and
    /// options.
    #[serde(default)]
    #[schemars(with = "BTreeMap<RuleKey, RuleEntry>")]
    pub rules: BTreeMap<RuleKey, Spanned<RuleEntry>>,
    /// Files generated by plugins' generators: `"<plugin>/<generator>" = { options = ... }`.
    #[serde(default)]
    #[schemars(with = "BTreeMap<PluginItem, GenerateEntry>")]
    pub generate: BTreeMap<PluginItem, Spanned<GenerateEntry>>,
    /// External commands, run by `gate run`.
    #[serde(default)]
    #[schemars(with = "BTreeMap<Name, Step>")]
    pub steps: BTreeMap<Name, Spanned<Step>>,
    /// Ordered lists of steps.
    #[serde(default)]
    #[schemars(with = "BTreeMap<Name, Suite>")]
    pub suites: BTreeMap<Name, Spanned<Suite>>,
    /// Whether every exception in the `gate.exceptions.toml` beside this file needs a decision.
    pub exception_policy: Option<ExceptionPolicy>,
    /// Root only: project settings for the projects whose roots match `projects`.
    #[serde(default)]
    #[schemars(with = "Vec<Profile>")]
    pub profiles: Vec<Spanned<Profile>>,
    /// Root only: how `gate run` runs steps.
    pub run: Option<RunSection>,
    /// Root only: git hooks and the gate commands they run.
    pub hooks: Option<HooksSection>,
    /// Root only: CI workflow jobs.
    pub ci: Option<CiSection>,
    /// Root only: external tools pinned by version and checksum.
    #[serde(default)]
    pub tools: BTreeMap<Name, Tool>,
}

/// A `[[profiles]]` entry: project settings for every project whose root matches `projects`.
///
/// A project gets, in order: the root's `[plugins]`, every matching profile in file order, its own
/// `gate.toml`. A later setting replaces an earlier one of the same key.
#[derive(Debug, Deserialize, JsonSchema)]
#[serde(deny_unknown_fields, rename_all = "kebab-case")]
pub struct Profile {
    /// Globs of project roots, relative to the repository root; `!` excludes.
    pub projects: Vec<String>,
    /// The presets the matching projects start from: `"<plugin>/<preset>"`.
    #[serde(default)]
    #[schemars(with = "Vec<PluginItem>")]
    pub extends: Vec<Spanned<PluginItem>>,
    /// Plugins for the matching projects.
    #[serde(default)]
    #[schemars(with = "BTreeMap<PluginName, PluginSpec>")]
    pub plugins: BTreeMap<PluginName, Spanned<PluginSpec>>,
    /// Language settings for the matching projects.
    #[serde(default)]
    #[schemars(with = "BTreeMap<Name, serde_json::Map<String, serde_json::Value>>")]
    pub languages: BTreeMap<Name, Spanned<serde_json::Value>>,
    /// Rule settings for the matching projects.
    #[serde(default)]
    #[schemars(with = "BTreeMap<RuleKey, RuleEntry>")]
    pub rules: BTreeMap<RuleKey, Spanned<RuleEntry>>,
    /// Generators for the matching projects.
    #[serde(default)]
    #[schemars(with = "BTreeMap<PluginItem, GenerateEntry>")]
    pub generate: BTreeMap<PluginItem, Spanned<GenerateEntry>>,
    /// Steps for the matching projects.
    #[serde(default)]
    #[schemars(with = "BTreeMap<Name, Step>")]
    pub steps: BTreeMap<Name, Spanned<Step>>,
    /// Suites for the matching projects.
    #[serde(default)]
    #[schemars(with = "BTreeMap<Name, Suite>")]
    pub suites: BTreeMap<Name, Spanned<Suite>>,
}

