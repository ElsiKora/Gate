//! The git hooks `gate sync` writes from `[hooks]`: POSIX `sh` scripts that call the launcher.
//!
//! A `run` entry passes the hook's own arguments to its steps (`-- "$@"`: the message file of
//! `commit-msg` is the steps' `$1`), and in `pre-push` the pushed refs on their standard input
//! (`--stdin`).

use std::fmt::Write as _;

use crate::config::{HooksSection, check_gate_command};
use crate::error::{Error, Result};

/// The directory the hooks are written to, and the value of `core.hooksPath`.
pub const HOOKS_DIRECTORY: &str = ".githooks";

/// The launcher every hook and job calls.
pub const LAUNCHER: &str = "bin/gate";

/// The second line of every generated hook.
pub const HOOK_MARKER: &str =
    "# Generated by gate sync from gate.toml [hooks]; edit gate.toml, then run gate sync.";

/// The hooks that receive the commit message file as `$1`.
const MESSAGE_HOOKS: &[&str] = &["applypatch-msg", "commit-msg", "prepare-commit-msg"];

/// The zero object id git uses for a ref that does not exist.
const ZERO: &str = "0000000000000000000000000000000000000000";

/// Every hook of `[hooks]`, as `(path, script)`.
///
/// # Errors
/// Fails when an entry is not a gate command a hook may run (see [`check_gate_command`]), or passes
/// `--push` outside `pre-push`, or `--commit-message` outside the hooks that receive a message
/// file.
pub fn scripts(hooks: &HooksSection) -> Result<Vec<(String, String)>> {
    let mut scripts = Vec::new();

    for (hook, commands) in &hooks.hooks {
        let hook = hook.as_str();
        let mut body = String::new();
        let _ = writeln!(body, "#!/bin/sh");
        let _ = writeln!(body, "{HOOK_MARKER}");
        let _ = writeln!(body, "set -e");
        for command in commands {
            check_gate_command(command).map_err(|message| {
                Error::config(format!("gate.toml: [hooks] {hook}: {message}"))
            })?;
        }
        let pushes = commands.iter().any(|command| has_flag(command, "--push"));
        if pushes && hook != "pre-push" {
            return Err(Error::config(format!(
                "gate.toml: [hooks] {hook}: \"--push\" checks the pushed refs, which only pre-push receives; use check --staged here"
            )));
        }
        let runs = |command: &String| command.split_whitespace().next() == Some("run");
        let feeds_refs = hook == "pre-push" && commands.iter().any(runs);
        if pushes || feeds_refs {
            let _ = writeln!(body, "refs=$(cat)");
        }

        for command in commands {
            let mut words: Vec<String> = command.split_whitespace().map(str::to_owned).collect();
            let is_check = words.first().is_some_and(|word| word == "check");

            if is_check
                && let Some(budget) = hooks.budget
                && !words.iter().any(|word| word == "--budget")
            {
                words.push("--budget".to_owned());
                words.push(budget.to_string());
            }

            // A check a hook starts says so: rules that apply only while a developer works read it.
            if is_check {
                words.push("--hook".to_owned());
            }

            if has_flag(command, "--commit-message") {
                if !MESSAGE_HOOKS.contains(&hook) {
                    return Err(Error::config(format!(
                        "gate.toml: [hooks] {hook}: \"--commit-message\" reads the message file, which only {} receive",
                        MESSAGE_HOOKS.join(", ")
                    )));
                }
                let at = words
                    .iter()
                    .position(|word| word == "--commit-message")
                    .unwrap_or(words.len());
                words.insert(at + 1, "\"$1\"".to_owned());
            }

            if has_flag(command, "--push") {
                let at = words
                    .iter()
                    .position(|word| word == "--push")
                    .unwrap_or(words.len());
                let rest = words.split_off(at + 1);
                words.extend([
                    "\"$remote_sha..$local_sha\"".to_owned(),
                    "--target-ref".to_owned(),
                    "\"$remote_ref\"".to_owned(),
                ]);
                words.extend(rest);
            }
            // The refs, each on its own line, for a run's --stdin; nothing when there is none.
            let mut input = "";
            if runs(command) {
                if feeds_refs {
                    words.push("--stdin".to_owned());
                    input = "{ [ -z \"$refs\" ] || printf '%s\\n' \"$refs\"; } | ";
                }
                words.push("--".to_owned());
                words.push("\"$@\"".to_owned());
            }

            if has_flag(command, "--push") {
                let _ = writeln!(
                    body,
                    "while read -r local_ref local_sha remote_ref remote_sha; do"
                );
                let _ = writeln!(body, "  [ -n \"$local_sha\" ] || continue");
                let _ = writeln!(body, "  [ \"$local_sha\" != {ZERO} ] || continue");
                // Each call reads nothing but what it is given: the loop's refs stay on the loop's
                // standard input.
                if input.is_empty() {
                    let _ = writeln!(body, "  {LAUNCHER} {} </dev/null", words.join(" "));
                } else {
                    let _ = writeln!(body, "  {input}{LAUNCHER} {}", words.join(" "));
                }
                let _ = writeln!(body, "done <<EOF");
                let _ = writeln!(body, "$refs");
                let _ = writeln!(body, "EOF");
            } else {
                let _ = writeln!(body, "{input}{LAUNCHER} {}", words.join(" "));
            }
        }

        scripts.push((format!("{HOOKS_DIRECTORY}/{hook}"), body));
    }

    Ok(scripts)
}

/// Whether the entry passes `flag`, alone or as `flag=value` (which [`check_gate_command`]
/// refuses).
fn has_flag(command: &str, flag: &str) -> bool {
    command.split_whitespace().any(|word| {
        word == flag
            || word
                .strip_prefix(flag)
                .is_some_and(|rest| rest.starts_with('='))
    })
}
