//! `agents/adapters`: the Claude Code adapters of the rule files (`.claude/rules/<stem>.md`) and
//! copies of the skills (`.claude/skills/**`).

use std::collections::BTreeMap;
use std::fmt::Write as _;

use gate_agents_format::RuleFile;
use gate_agents_format::markdown::body;
use gate_sdk::{Generate, Generator, Location, Result};

use crate::load::{Agents, RootOptions, strict_text};

/// The generator.
#[derive(Debug, Default)]
pub struct Adapters;

impl Generator for Adapters {
    type Options = RootOptions;

    const NAME: &'static str = "adapters";
    const TITLE: &'static str = "Claude Code adapters of the rule files and skills";
    const OWNS: &'static [&'static str] = &[".claude/rules/**", ".claude/skills/**"];

    fn generate(&self, run: &mut Generate<'_, RootOptions>) -> Result<()> {
        let tree = run.tree();
        let agents = Agents::load(&tree, &run.options().root)?;
        let skills_dir = agents.skills_dir();
        let mut files: Vec<(String, Vec<u8>)> = Vec::new();

        // A rule file without valid front matter gets no adapter: its scope is unknown, and
        // `agents/rule-registry` reports the file. Two rule files whose adapter paths are equal
        // ignoring case (on a case-insensitive file system they are one file) get none either.
        let mut by_path: BTreeMap<String, Vec<&RuleFile>> = BTreeMap::new();
        for file in agents
            .rules
            .iter()
            .filter(|file| file.frontmatter.is_some())
        {
            by_path
                .entry(adapter_path(file).to_lowercase())
                .or_default()
                .push(file);
        }
        for sources in by_path.into_values() {
            match sources.as_slice() {
                [file] => {
                    let text = strict_text(&tree, &file.path)?.unwrap_or_default();
                    files.push((adapter_path(file), adapter(file, &text).into_bytes()));
                }
                colliding => {
                    let names: Vec<&str> =
                        colliding.iter().map(|file| file.path.as_str()).collect();
                    for file in colliding {
                        run.report()
                            .finding(
                                "",
                                Location::file(&file.path),
                                format!(
                                    "{} map to one adapter, {}; none is written",
                                    names.join(" and "),
                                    adapter_path(file)
                                ),
                            )
                            .key(adapter_path(file))
                            .target(file.path.clone())
                            .help("rename the rule files so their names differ by more than case or a second `.md`");
                    }
                }
            }
        }
        for skill in &agents.skills {
            for source in &skill.files {
                if let Some(bytes) = tree.bytes(source) {
                    let relative = &source[skills_dir.len() + 1..];
                    files.push((format!(".claude/skills/{relative}"), bytes));
                }
            }
        }
        for (path, contents) in files {
            run.write(path, contents);
        }
        Ok(())
    }
}

fn quote(value: &str) -> String {
    format!("\"{}\"", value.replace('\\', "\\\\").replace('"', "\\\""))
}

/// Where the adapter of a rule file is written.
fn adapter_path(file: &RuleFile) -> String {
    format!(".claude/rules/{}.md", file.stem)
}

/// The adapter of one rule file: the `paths:` scope, then a copy of the body.
///
/// Claude Code documents `@` imports only for `CLAUDE.md` and `AGENTS.md`, so the adapter copies
/// the text instead of importing it, and `gate sync --check` rejects any edit of the copy.
fn adapter(file: &RuleFile, text: &str) -> String {
    let mut output = String::new();
    if file.applies() == Some("globs") {
        output.push_str("---\npaths:\n");
        for glob in file.globs() {
            let _ = writeln!(output, " - {}", quote(glob));
        }
        output.push_str("---\n\n");
    }
    let _ = writeln!(
        output,
        "<!-- Generated by gate sync from {}; edit the canonical file. -->\n",
        file.path
    );
    output.push_str(body(text).trim_start_matches('\n'));
    output
}
