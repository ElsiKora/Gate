//! The generators: Claude Code adapters and the `AGENTS.md` block, byte for byte.

use gate_sdk::GenerateOutput;

use crate::fixture::{Fixture, always, lines};

const API: &str = "---\ntitle: API rules\narea: API\napplies: globs\nglobs: [\"src/**/*.ts\", \"lib/a\\\"b\"]\nowner: D-ONE-001\n---\n\n\n# API\n\nBody.\n";

fn files(output: &GenerateOutput) -> Vec<(&str, String)> {
    output
        .files
        .iter()
        .map(|file| {
            (
                file.path.as_str(),
                String::from_utf8_lossy(&file.contents).into_owned(),
            )
        })
        .collect()
}

fn tree(entry: Option<&str>) -> Fixture {
    let ops = always("OPS", 1);
    let mut files = vec![
        ("docs/agents/rules/api.md", API),
        ("docs/agents/rules/ops.md", ops.as_str()),
        ("docs/agents/skills/tool/SKILL.md", "---\nname: tool\n---\n"),
        ("docs/agents/skills/tool/bin/run.sh", "#!/bin/sh\n"),
        (".claude/rules/api.md", "edited by hand\n"),
        (".claude/rules/old.md", "stale\n"),
        (".claude/skills/gone/SKILL.md", "stale\n"),
    ];
    if let Some(entry) = entry {
        files.push(("AGENTS.md", entry));
    }
    Fixture::new(&files)
}

const API_ADAPTER: &str = "---\npaths:\n - \"src/**/*.ts\"\n - \"lib/a\\\"b\"\n---\n\n<!-- Generated by gate sync from docs/agents/rules/api.md; edit the canonical file. -->\n\n# API\n\nBody.\n";
const OPS_ADAPTER: &str = "<!-- Generated by gate sync from docs/agents/rules/ops.md; edit the canonical file. -->\n\n# Rules\n\n## RULE-OPS-001 Rule 1\n\nEnforcement: gate · Status: stable\n\n";

#[test]
fn adapters_copy_rule_bodies_under_their_scope_and_skills_byte_for_byte_and_leave_stale_files_to_the_core()
 {
    let output = tree(None).generate("adapters", "", "{}").expect("runs");
    assert_eq!(
        files(&output),
        [
            (".claude/rules/api.md", API_ADAPTER.to_owned()),
            (".claude/rules/ops.md", OPS_ADAPTER.to_owned()),
            (
                ".claude/skills/tool/SKILL.md",
                "---\nname: tool\n---\n".to_owned()
            ),
            (".claude/skills/tool/bin/run.sh", "#!/bin/sh\n".to_owned()),
        ]
    );
    assert_eq!(output.findings, []);
}

#[test]
fn adapters_paths_are_project_relative_and_the_adapter_directories_are_owned() {
    let output = tree(None)
        .generate("adapters", "apps/web", "{}")
        .expect("runs");
    let paths: Vec<&str> = output.files.iter().map(|file| file.path.as_str()).collect();
    assert_eq!(
        paths,
        [
            ".claude/rules/api.md",
            ".claude/rules/ops.md",
            ".claude/skills/tool/SKILL.md",
            ".claude/skills/tool/bin/run.sh",
        ]
    );
    let info = gate_sdk::describe(&agents::PLUGIN);
    let owns: Vec<(&str, Vec<&str>)> = info
        .generators
        .iter()
        .map(|generator| {
            (
                generator.name.as_str(),
                generator.owns.iter().map(String::as_str).collect(),
            )
        })
        .collect();
    assert_eq!(
        owns,
        [
            ("adapters", vec![".claude/rules/**", ".claude/skills/**"]),
            ("agents-block", vec![]),
        ]
    );
}

fn row(cells: [&str; 4]) -> String {
    format!(
        "| {:<5} | {:<37} | {:<24} | {:<11} |\n",
        cells[0], cells[1], cells[2], cells[3]
    )
}

#[test]
fn the_agents_block_lists_every_rule_file_between_its_markers() {
    let entry = "# Agents\n\n<!-- gate:begin agents -->\nold\n<!-- gate:end agents -->\n\nTail.\n";
    let output = tree(Some(entry))
        .generate("agents-block", "", "{}")
        .expect("runs");
    let table = [
        row(["Area", "Rules", "Applies", "Owner"]),
        row(["-----", &"-".repeat(37), &"-".repeat(24), &"-".repeat(11)]),
        row([
            "`API`",
            "[API rules](docs/agents/rules/api.md)",
            "`src/**/*.ts`, `lib/a\"b`",
            "`D-ONE-001`",
        ]),
        row([
            "`OPS`",
            "[ops](docs/agents/rules/ops.md)",
            "always",
            "`D-ONE-001`",
        ]),
    ]
    .concat();
    let expected = format!(
        "# Agents\n\n<!-- gate:begin agents -->\n\n\
         Generated by `bin/gate sync` from `docs/agents/rules`; edit the rule files, not this block.\n\n\
         {table}\nAlways-apply rules:\n\n- [ops](docs/agents/rules/ops.md)\n\n\
         <!-- gate:end agents -->\n\nTail.\n"
    );
    assert_eq!(files(&output), [("AGENTS.md", expected)]);
    assert_eq!(output.findings, []);

    let renamed = tree(Some(entry))
        .generate("agents-block", "", r#"{"command-text": "make sync"}"#)
        .expect("runs");
    assert!(
        files(&renamed)[0]
            .1
            .contains("Generated by `make sync` from")
    );
}

#[test]
fn the_agents_block_needs_one_pair_of_markers_and_a_tracked_entry() {
    let missing = tree(Some("# Agents\n"))
        .generate("agents-block", "", "{}")
        .expect("runs");
    assert_eq!(missing.files, []);
    assert_eq!(
        lines(&missing.findings),
        [
            "AGENTS.md the managed block `<!-- gate:begin agents -->` … `<!-- gate:end agents -->` is missing"
        ]
    );

    let twice = tree(Some(
        "<!-- gate:begin agents -->\n<!-- gate:begin agents -->\n<!-- gate:end agents -->\n",
    ))
    .generate("agents-block", "", "{}")
    .expect("runs");
    assert_eq!(
        lines(&twice.findings),
        [
            "AGENTS.md:1 the managed block agents needs exactly one `<!-- gate:begin agents -->` line followed by one `<!-- gate:end agents -->` line"
        ]
    );

    // A block with no rule file lists nothing: a finding of `gate sync`, never a silent pass.
    let no_rules_message = "docs/agents/rules docs/agents/rules has no rule file, and agents/agents-block reads the rule files there (its option root); create a rule file docs/agents/rules/<area>.md, point root at the agent docs, or remove the generator from [generate]";
    let no_rules = Fixture::new(&[("AGENTS.md", "# Agents\n")]);
    let output = no_rules.generate("agents-block", "", "{}").expect("runs");
    assert_eq!(output.files, []);
    assert_eq!(lines(&output.findings), [no_rules_message]);

    // With no entry either, the entry is seeded and the missing rule files stay the finding.
    let absent = Fixture::new(&[("README.md", "# Project\n")]);
    let output = absent.generate("agents-block", "", "{}").expect("runs");
    assert_eq!(
        output
            .files
            .iter()
            .map(|file| (file.path.as_str(), file.seed))
            .collect::<Vec<_>>(),
        [("AGENTS.md", true)]
    );
    assert_eq!(lines(&output.findings), [no_rules_message]);

    let emptied = Fixture::new(&[(
        "AGENTS.md",
        "<!-- gate:begin agents -->\nold\n<!-- gate:end agents -->\n",
    )]);
    let output = emptied.generate("agents-block", "", "{}").expect("runs");
    assert_eq!(
        files(&output),
        [(
            "AGENTS.md",
            "<!-- gate:begin agents -->\n\n<!-- gate:end agents -->\n".to_owned()
        )]
    );
    assert_eq!(lines(&output.findings), [no_rules_message]);
}

#[test]
fn adapters_skip_files_without_front_matter_and_refuse_colliding_paths() {
    let ops = always("OPS", 1);
    let crlf = ops.replace('\n', "\r\n");
    let fixture = Fixture::new(&[
        ("docs/agents/rules/ops.md", ops.as_str()),
        ("docs/agents/rules/bare.md", "# No front matter\n"),
        (
            "docs/agents/rules/broken.md",
            "---\narea: [\n---\n# Broken\n",
        ),
        ("docs/agents/rules/windows.md", crlf.as_str()),
        ("docs/agents/rules/twin.md", ops.as_str()),
        ("docs/agents/rules/TWIN.MD", ops.as_str()),
        ("docs/agents/rules/notes.md.md", ops.as_str()),
    ]);
    let output = fixture.generate("adapters", "", "{}").expect("runs");
    let paths: Vec<&str> = output.files.iter().map(|file| file.path.as_str()).collect();
    assert_eq!(paths, [".claude/rules/notes.md.md", ".claude/rules/ops.md"]);
    assert_eq!(
        lines(&output.findings),
        [
            "docs/agents/rules/TWIN.MD docs/agents/rules/TWIN.MD and docs/agents/rules/twin.md map to one adapter, .claude/rules/TWIN.md; none is written",
            "docs/agents/rules/twin.md docs/agents/rules/TWIN.MD and docs/agents/rules/twin.md map to one adapter, .claude/rules/twin.md; none is written",
        ]
    );
}

#[test]
fn the_agents_block_links_relative_to_its_entry_and_escapes_pipes() {
    let rule = "---\ntitle: A | B\narea: API\napplies: always\nowner: D-ONE-001\n---\n# A\n";
    let fixture = Fixture::new(&[
        (
            "docs/AGENTS.md",
            "<!-- gate:begin agents -->\n<!-- gate:end agents -->\n",
        ),
        ("docs/agents/rules/api.md", rule),
    ]);
    let output = fixture
        .generate("agents-block", "", r#"{"entry": "docs/AGENTS.md"}"#)
        .expect("runs");
    let written = &files(&output)[0].1;
    assert!(
        written.contains("[A \\| B](agents/rules/api.md)"),
        "{written}"
    );
    assert!(
        written.contains("- [A \\| B](agents/rules/api.md)\n"),
        "{written}"
    );
}

/// An entry that is not tracked is seeded: a title, one line, and the block filled as the generator
/// fills it, so the next run over the seeded file writes the same bytes. A tracked entry is written,
/// never seeded.
#[test]
fn an_untracked_entry_is_seeded_with_its_block_and_the_next_run_writes_the_same_bytes() {
    let header = "# Agent instructions\n\nThe entry point for coding agents in this project: the rule files below apply to their areas.\n\n";
    for (name, fixture, entry, options) in [
        ("rules", tree(None), "AGENTS.md", "{}"),
        (
            "no rules",
            Fixture::new(&[("README.md", "# Project\n")]),
            "AGENTS.md",
            "{}",
        ),
        (
            "nested entry",
            tree(None),
            "docs/AGENTS.md",
            r#"{"entry": "docs/AGENTS.md"}"#,
        ),
    ] {
        let output = fixture.generate("agents-block", "", options).expect("runs");
        assert_eq!(output.files.len(), 1, "{name}");
        let seeded = &output.files[0];
        assert_eq!((seeded.path.as_str(), seeded.seed), (entry, true), "{name}");
        let text = String::from_utf8(seeded.contents.clone()).expect("UTF-8");
        assert!(text.starts_with(header), "{name}: {text}");
        assert!(
            text.contains("<!-- gate:begin agents -->\n")
                && text.ends_with("<!-- gate:end agents -->\n"),
            "{name}: {text}"
        );
        if name == "no rules" {
            assert_eq!(
                text,
                format!("{header}<!-- gate:begin agents -->\n\n<!-- gate:end agents -->\n"),
            );
        } else {
            assert!(text.contains("| `API` |"), "{name}: {text}");
        }

        let tracked = fixture.with_bytes(entry, text.as_bytes());
        let again = tracked.generate("agents-block", "", options).expect("runs");
        assert_eq!(
            again
                .files
                .iter()
                .map(|file| (file.path.as_str(), file.seed, file.contents.as_slice()))
                .collect::<Vec<_>>(),
            [(entry, false, text.as_bytes())],
            "{name}"
        );
    }
}
